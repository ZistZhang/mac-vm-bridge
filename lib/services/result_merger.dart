import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:archive/archive_io.dart';
import 'package:path/path.dart' as p;

import '../models/app_settings.dart';
import '../models/document_job.dart';
import '../utils/file_utils.dart';

class MergeResult {
  const MergeResult({
    required this.outputDirectory,
    required this.markdownPath,
    required this.packageZipPath,
  });

  final String outputDirectory;
  final String markdownPath;
  final String packageZipPath;
}

class ResultMerger {
  Future<String> extractZip({
    required String zipPath,
    required String destination,
  }) async {
    final output = Directory(destination);
    if (await output.exists()) await output.delete(recursive: true);
    await output.create(recursive: true);

    final bytes = await File(zipPath).readAsBytes();
    final archive = ZipDecoder().decodeBytes(bytes, verify: true);
    for (final item in archive) {
      final normalized = p.normalize(item.name.replaceAll('\\', '/'));
      if (normalized.startsWith('..') || p.isAbsolute(normalized)) continue;
      final target = p.join(output.path, normalized);
      if (item.isFile) {
        final file = File(target);
        await file.parent.create(recursive: true);
        final content = item.content;
        if (content is List<int>) {
          await file.writeAsBytes(content, flush: true);
        }
      } else {
        await Directory(target).create(recursive: true);
      }
    }
    return output.path;
  }

  Future<MergeResult> merge({
    required DocumentJob job,
    required AppSettings settings,
  }) async {
    final stem = safeStem(job.originalName);
    final exportRoot = Directory(p.join(job.workspacePath, 'export'));
    if (await exportRoot.exists()) await exportRoot.delete(recursive: true);
    await exportRoot.create(recursive: true);

    final output = Directory(p.join(exportRoot.path, stem));
    final assets = Directory(p.join(output.path, 'assets'));
    final rawChunks = Directory(p.join(output.path, 'raw-chunks'));
    await assets.create(recursive: true);
    if (settings.keepRawChunks) await rawChunks.create(recursive: true);

    final merged = StringBuffer();
    merged.writeln('<!-- Generated by MinerU Flow -->');
    merged.writeln('<!-- Source: ${job.originalName} -->');
    if (job.totalPages != null) {
      merged.writeln('<!-- Original pages: ${job.totalPages} -->');
    }

    for (final chunk in [...job.chunks]..sort((a, b) => a.index.compareTo(b.index))) {
      final extractedPath = chunk.extractedPath;
      if (extractedPath == null) {
        throw StateError('分片 ${chunk.index + 1} 缺少解压目录');
      }
      final extracted = Directory(extractedPath);
      final markdownFile = await findFileNamed(extracted, 'full.md');
      if (markdownFile == null) {
        throw StateError('分片 ${chunk.index + 1} 的结果中未找到 full.md');
      }

      var markdown = await markdownFile.readAsString();
      markdown = await _copyAndRewriteAssets(
        markdown: markdown,
        markdownDirectory: markdownFile.parent,
        extractedRoot: extracted,
        assetsDirectory: assets,
        prefix: 'part${(chunk.index + 1).toString().padLeft(3, '0')}_',
      );

      merged
        ..writeln()
        ..writeln(
          '<!-- ===== MinerU Flow part ${chunk.index + 1}/${job.chunks.length}; original pages ${chunk.startPage}-${chunk.endPage} ===== -->',
        )
        ..writeln()
        ..write(markdown.trim())
        ..writeln();

      if (settings.keepRawChunks) {
        await _copyDirectory(
          extracted,
          Directory(
            p.join(
              rawChunks.path,
              'part-${(chunk.index + 1).toString().padLeft(3, '0')}',
            ),
          ),
        );
      }
    }

    final markdownPath = p.join(output.path, 'document.md');
    await File(markdownPath).writeAsString(merged.toString(), flush: true);

    final sourceHash = await sha256File(File(job.sourcePath));
    final manifest = {
      'schema': 1,
      'generator': 'MinerU Flow 0.1.0',
      'generatedAt': DateTime.now().toIso8601String(),
      'source': {
        'name': job.originalName,
        'sha256': sourceHash,
        'pages': job.totalPages,
      },
      'settings': settings.toJson(),
      'chunks': job.chunks
          .map(
            (chunk) => {
              'index': chunk.index + 1,
              'sourcePages': '${chunk.startPage}-${chunk.endPage}',
              'sizeBytes': chunk.sizeBytes,
              'batchId': chunk.batchId,
            },
          )
          .toList(),
      'files': {
        'markdown': 'document.md',
        'assets': 'assets/',
        'rawChunks': settings.keepRawChunks ? 'raw-chunks/' : null,
      },
    };
    await File(p.join(output.path, 'manifest.json')).writeAsString(
      const JsonEncoder.withIndent('  ').convert(manifest),
      flush: true,
    );

    await File(p.join(output.path, 'README_FOR_AGENT.md')).writeAsString(
      '''# Agent reading instructions

`document.md` is the merged Markdown representation of `${job.originalName}`.

- Read `document.md` from beginning to end.
- HTML comments mark technical MinerU API chunk boundaries; they are not semantic chapter boundaries.
- Images referenced by Markdown are under `assets/`.
- `manifest.json` maps every API chunk back to original page ranges.
${settings.keepRawChunks ? '- `raw-chunks/` preserves unmodified MinerU outputs for audit and recovery.\n' : ''}
''',
      flush: true,
    );

    final zipPath = p.join(exportRoot.path, '$stem-agent-package.zip');
    final encoder = ZipFileEncoder();
    encoder.create(zipPath);
    encoder.addDirectory(output, includeDirName: true);
    encoder.close();

    return MergeResult(
      outputDirectory: output.path,
      markdownPath: markdownPath,
      packageZipPath: zipPath,
    );
  }

  Future<String> _copyAndRewriteAssets({
    required String markdown,
    required Directory markdownDirectory,
    required Directory extractedRoot,
    required Directory assetsDirectory,
    required String prefix,
  }) async {
    final replacements = <String, String>{};
    final referenced = <String>{};

    final markdownImages = RegExp(r'!\[([^\]]*)\]\(([^)]+)\)');
    for (final match in markdownImages.allMatches(markdown)) {
      final raw = match.group(2)!.trim().replaceAll(RegExp(r'^<|>$'), '');
      if (_isRemote(raw)) continue;
      referenced.add(raw);
    }
    final htmlImages = RegExp(r'''<img\s+[^>]*src=["']([^"']+)["'][^>]*>''', caseSensitive: false);
    for (final match in htmlImages.allMatches(markdown)) {
      final raw = match.group(1)!.trim();
      if (_isRemote(raw)) continue;
      referenced.add(raw);
    }

    for (final raw in referenced) {
      final decoded = Uri.decodeFull(raw.split('#').first.split('?').first);
      final candidates = [
        File(p.normalize(p.join(markdownDirectory.path, decoded))),
        File(p.normalize(p.join(extractedRoot.path, decoded))),
      ];
      File? source;
      for (final candidate in candidates) {
        if (await candidate.exists()) {
          source = candidate;
          break;
        }
      }
      if (source == null) continue;
      final safeName = safeFileName(p.basename(source.path));
      final destinationName = '$prefix$safeName';
      final destination = File(p.join(assetsDirectory.path, destinationName));
      await source.copy(destination.path);
      replacements[raw] = 'assets/$destinationName';
    }

    var rewritten = markdown;
    for (final entry in replacements.entries) {
      rewritten = rewritten.replaceAll(entry.key, entry.value);
    }
    return rewritten;
  }

  bool _isRemote(String value) {
    final lower = value.toLowerCase();
    return lower.startsWith('http://') ||
        lower.startsWith('https://') ||
        lower.startsWith('data:') ||
        lower.startsWith('mailto:');
  }

  Future<void> _copyDirectory(Directory source, Directory destination) async {
    await destination.create(recursive: true);
    await for (final entity in source.list(recursive: false, followLinks: false)) {
      final targetPath = p.join(destination.path, p.basename(entity.path));
      if (entity is Directory) {
        await _copyDirectory(entity, Directory(targetPath));
      } else if (entity is File) {
        await entity.copy(targetPath);
      }
    }
  }
}
